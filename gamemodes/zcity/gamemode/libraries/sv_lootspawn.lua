        SetupLootItemDespawn(ent2)
    end,
    Armor = function(ent, armor)
        local ent2 = ents_Create("ent_armor_" .. armor)
        if not IsValid(ent2) then return end
        ent2:SetPos(ent:GetPos())
        ent2:SetAngles(ent:GetAngles())
