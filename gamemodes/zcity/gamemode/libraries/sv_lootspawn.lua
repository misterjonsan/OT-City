        weapon:SetPos(ent:GetPos())
        weapon:SetAngles(ent:GetAngles())
        weapon:Spawn()
        weapon.IsSpawned = true
        weapon.init = true

        if weapon.SetInfo then
            weapon:SetInfo(stored)
        end

        SetupLootItemDespawn(weapon)
    end,
    Ammo = function(ent, ammo)
        local ammoId = isnumber(ammo) and ammo or game_GetAmmoID(hg.ammotypes[ammo].name)
        local ammoGameName = ammoId and game_GetAmmoName(ammoId)
