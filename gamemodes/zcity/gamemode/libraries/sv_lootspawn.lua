    if not IsValid(ent) or ent:IsPlayer() or ent.was_opened or not string_find(ent:GetClass(), "prop_", 1, true) then return end

    local lootData = GetLootBoxData(ent)
    if not lootData then return end

    ent.armors = {}
    ent.inventory = {}
    ent.was_opened = true

    local size = lootData[1] or 1
    local chance = hg.loot_amount[size] or {0, 1}
    local amount = math_random(chance[1], chance[2])

    for _ = 1, amount do
        local entName, AmmoCount, Tab = hg.GenerateLoot(ply, ent)
        if entName and functions[Tab] then
            entName = string_Replace(entName, "ent_att_", "")
            entName = string_Replace(entName, "ent_armor_", "")
            entName = string_Replace(entName, "ent_ammo_", "")
            functions[Tab](ent, entName, AmmoCount)
        end
    end

    ent:SetNetVar("Armor", ent.armors)
    ent:SetNetVar("Inventory", ent.inventory)
end)

