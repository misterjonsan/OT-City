local vecHull = Vector(0, 0, 0)
local trCheck = {
    mask = MASK_SOLID,
    mins = -vecHull,
    maxs = vecHull,
}

local spawns = {}
local spawnPointsForBuild = {}

local function MakeRandomSpawns(basepoints, maxiterations, out)
    local count = #basepoints
    if count == 0 then return out end

    for _ = 1, maxiterations do
        local base = basepoints[math_random(count)]
        if base then
            local vecRand = VectorRand(-2048, 2048)
            vecRand[3] = math_random(8) == 1 and math_abs(vecRand[3]) / math_random(2) or 0

            local start = base + vecRand
            local tr = util_TraceLine({
                start = start,
                endpos = start + -vector_up * 256,
                mask = bit_bor(MASK_SOLID, MASK_WATER)
            })

            if tr.Hit and not tr.HitSky and not tr.StartedSolid and tr.HitTexture ~= "**studio**" and tr.HitTexture ~= "**empty**" and tr.HitTexture ~= "TOOLS/TOOLSNODRAW" and tr.MatType ~= MAT_SLOSH then
                local hitPos = tr.HitPos
                local pos = hitPos + vector_up * 16

                trCheck.start = hitPos
                trCheck.endpos = hitPos + vector_up * 36

                local tr2 = util_TraceLine(trCheck)

                if not tr2.Hit and not tr2.StartedSolid and tr2.HitTexture ~= "**studio**" then
                    count = count + 1
                    basepoints[count] = pos
                    out[#out + 1] = pos
                end
            end
        end
    end

    return out
end

local function RebuildSpawns()
    spawns = {}

    for _, ent in ipairs(ents_FindByClass("info_*")) do
        spawns[#spawns + 1] = ent:GetPos()
    end

    local navmeshareas = navmesh.GetAllNavAreas()
    for i = 1, #navmeshareas do
        local area = navmeshareas[i]
        if not area:IsUnderwater() then
            spawns[#spawns + 1] = area:GetCenter()
        end
    end

    spawnPointsForBuild = {}
    table_CopyFromTo(spawns, spawnPointsForBuild)

    local extra = MakeRandomSpawns(spawnPointsForBuild, math.min(500, math.max(100, #spawns * 0.35)), {})
    if #extra > 0 then
        local translated = zb.TranslateVectorsToPoints(extra)
        zb.SaveMapPoints("RandomSpawns", translated)
        table_Add(spawns, extra)
    end

    hg.spawn_cache_ready = #spawns > 0
end

local function GetAlivePlayers()
    local all = player_GetAll()
    local alive = {}

    for i = 1, #all do
        local ply = all[i]
        if IsValid(ply) and ply:Alive() then
            alive[#alive + 1] = ply
        end
    end

    return alive
end

local function GetAreaScoreNearPlayer(ply)
    local score = 1
    local origin = ply:EyePos()

    for i = 1, 4 do
        local dir = VectorRand(-1, 1)
        dir[3] = 0
        dir:Normalize()

        local tr = util_TraceLine({
            start = origin,
            endpos = origin + dir * 512,
            filter = ply,
            collisiongroup = COLLISION_GROUP_PLAYER
        })

        if not tr.Hit then
            score = score + 2
        else
            local dist = origin:Distance(tr.HitPos)
            score = score + math_Clamp(dist / 128, 0, 2)
        end
    end

    return math_Clamp(math.floor(score), 1, 10)
end

local function FindSpawnPosNearPlayer(ply, desiredSize)
    local vel = ply:GetVelocity() * math_random(1, 100) + VectorRand(-1024, 1024)
    vel[3] = 0

    local pos = ply:EyePos()
    local trace = util_TraceLine({
        start = pos,
        endpos = pos + vel,
        filter = ply,
        collisiongroup = COLLISION_GROUP_PLAYER
    })

    local searchSteps = math_Clamp(3 + desiredSize, 4, 12)

    for _ = 1, searchSteps do
        local tr = {}
        tr.start = trace.HitPos - trace.Normal * 16
        tr.endpos = tr.start + VectorRand(-1024 - desiredSize * 48, 1024 + desiredSize * 48)
        tr.filter = ply
        tr.collisiongroup = COLLISION_GROUP_PLAYER

        trace = util_TraceLine(tr)
        trace = util_QuickTrace(trace.HitPos, -vector_up * (768 + desiredSize * 32), ply)
    end

    return trace.HitPos + vector_up * 32 - trace.Normal * 10
end

local vec_dist = Vector(500, 500, 500)

local function CanSpawnBoxAt(spawnPos)
    if CurrentRound().noBoxes then return true end

    local near = ents_FindInBox(spawnPos - vec_dist, spawnPos + vec_dist)
    for i = 1, #near do
        local ply = near[i]
        if ply:IsPlayer() and ply:Alive() then
            local tr = util_TraceLine({
                start = spawnPos,
                endpos = ply:EyePos(),
                mask = MASK_VISIBLE
            })

            if IsValid(tr.Entity) and tr.Entity == ply then
                return false
            end
        end
    end

    return true
end

local function TrySpawnWorldProp(spawnPos, desiredSize)
    local model

    if math_random(6) == 1 then
        model = PickRandomFromSizedPool(hg.spawn_prop_models_by_size, hg.spawn_prop_models, desiredSize, 3)
    else
        model = PickRandomFromSizedPool(hg.loot_box_models_by_size, hg.loot_box_models, desiredSize, 2)
    end

    if not model or not util_IsValidProp(model) then return end

    local ent = ents_Create("prop_physics")
    if not IsValid(ent) then return end

    ent:SetPos(spawnPos)
    ent:SetModel(model)

    local trace = util_TraceEntity({
        start = spawnPos,
        endpos = spawnPos,
        collisiongroup = COLLISION_GROUP_WORLD
    }, ent)

    if trace.Hit then
        ent:Remove()
        return
    end

    ent:Spawn()
    return true
end

local function TrySpawnLootEntity(spawnPos)
    local entName, AmmoCount = hg.GenerateLoot()
    if not entName or entName == "" then return end

    local ent = ents_Create(entName)
    if not IsValid(ent) then return end

    ent.IsSpawned = true
    ent:SetPos(spawnPos)
    ent:Spawn()
    ent.init = true

    if AmmoCount then
        ent.AmmoCount = AmmoCount
    end

    SetupLootItemDespawn(ent)
    return true
end

