hook.Add("Boxes Think", "SpawnBoxes", function()
    local round = CurrentRound()
    if zb.ROUND_STATE ~= 1 or not round.LootSpawn then return end

    local alivePlayers = GetAlivePlayers()
    if #alivePlayers == 0 then return end

    local ply = alivePlayers[math_random(#alivePlayers)]
    local areaScore = GetAreaScoreNearPlayer(ply)
    local desiredSize = math_Clamp(areaScore + math_random(-1, 2), 1, 10)
    local spawnPos = FindSpawnPosNearPlayer(ply, desiredSize)

    if not CanSpawnBoxAt(spawnPos) then return end

    local propChance = 0.35 + desiredSize * 0.035
    if not round.noBoxes and math_Rand(0, 1) <= math.min(propChance, 0.8) then
        if TrySpawnWorldProp(spawnPos, desiredSize) then
            return
        end
    end

    TrySpawnLootEntity(spawnPos)
end)