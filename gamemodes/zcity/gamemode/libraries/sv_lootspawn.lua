local function PickRandomFromSizedPool(poolBySize, fallbackPool, wantedSize, variance)
    variance = variance or 2
    local minSize = math.max(1, wantedSize - variance)
    local maxSize = math.min(10, wantedSize + variance)

    for _ = 1, 8 do
        local size = math_random(minSize, maxSize)
        local bucket = poolBySize[size]
        if bucket and #bucket > 0 then
            return bucket[math_random(#bucket)]
        end
    end

    if #fallbackPool > 0 then
        return fallbackPool[math_random(#fallbackPool)]
    end
end

local function SetupLootItemDespawn(ent)
    if not IsValid(ent) then return end

    local lifeTime = loot_item_lifetime:GetFloat()
    if lifeTime <= 0 then return end

    ent.hg_loot_spawned_at = CurTime()
    ent.hg_loot_remove_at = CurTime() + lifeTime
    ent.hg_loot_should_remove = true

    local timerName = "hg_loot_despawn_" .. ent:EntIndex()
    timer.Remove(timerName)

    timer.Create(timerName, lifeTime, 1, function()
        if not IsValid(ent) then return end
        if not ent.hg_loot_should_remove then return end
        if ent:IsPlayerHolding() then
            SetupLootItemDespawn(ent)
            return
        end
        ent:Remove()
    end)

    ent:CallOnRemove("hg_loot_despawn_cleanup", function(self)
        timer.Remove("hg_loot_despawn_" .. self:EntIndex())
    end)
end

local function MarkLootEntityPersistent(ent)
    if not IsValid(ent) then return end
    ent.hg_loot_should_remove = false
    timer.Remove("hg_loot_despawn_" .. ent:EntIndex())
end

function hg.GenerateLoot(ply, ent, func)
    local curRound, rtype = CurrentRound()
    local should = curRound.LootSpawn

    if not (should or (curRound.Lootables and IsValid(ent) and curRound.Lootables[ent:GetModel()])) then
        return
    end

    local traitor_opened = IsValid(ply) and ply.isTraitor
    local low_karma_player = IsValid(ply) and (ply.Karma < 70)
    local very_low_karma_player = IsValid(ply) and (ply.Karma < 30)
    local high_karma_player = IsValid(ply) and (ply.Karma >= zb.MaxKarma)
    local time = CurTime() - (zb.ROUND_START or CurTime())

    local mul = hook_Run("ZB_LootMultiplier", ply)

    if not mul then
        mul = traitor_opened and 1.5 or (very_low_karma_player and 0.25 or (low_karma_player and 0.5 or (high_karma_player and 1.25 or 1)))
    end

    if ent then
        local size = GetModelSize(ent)
        mul = mul * (0.7 + size * 0.08)
    end

    if curRound.LootOnTime then
        local div = curRound.LootDivTime or 300
        mul = math_Rand(1, math_Clamp(mul * (time / div), 0.25, 1.75))
        if developer:GetBool() and IsValid(ply) then
            timer.Simple(0, function()
                if IsValid(ply) then
                    ply:ChatPrint("sv_lootspawn: MUL = " .. mul .. " TIME/" .. div .. " = " .. (time / div) .. " TIME = " .. time)
                end
            end)
        end
    end

    local entName, AmmoCount, Tab
    Tab = "Weapons"

    local tab = curRound.GetLootTable and curRound:GetLootTable()

    if not tab then
        local cur = curRound.Type and curRound.Types[rtype] or curRound
        local chances = cur.LootTable or curRound.LootTable or zb.modes["hmcd"].LootTable
        local _, tabs = hg.WeightedRandomSelect(chances, mul)
        tab = tabs

        if curRound.name == "pathowogen" and time < 90 then
            tab = chances[1][2]
        end
    end

    local _, pickedEnt = hg.WeightedRandomSelect(tab)
    entName = pickedEnt

    if hg.PluvTown.Active and (entName == "weapon_bigconsumable" or entName == "weapon_smallconsumable") then
        entName = "weapon_pluviska"
    end

    if entName then
        if entName == "*ammo*" or string_find(entName, "ent_ammo", 1, true) then
            Tab = "Ammo"

            if not string_find(entName, "ent_ammo", 1, true) then
                local ammo

                if IsValid(ply) and math_random(3) == 1 then
                    for _, wep in RandomPairs(ply:GetWeapons()) do
                        if wep:GetMaxClip1() > 0 and wep.Primary and wep.Primary.Ammo and hg.ammotypeshuy[wep.Primary.Ammo] then
                            ammo = hg.ammotypeshuy[wep.Primary.Ammo].name
                            break
                        end
                    end
                end

                if not ammo then
                    ammo = table.Random(hg.ammotypesallowed).name
                end

                if ammo then
                    entName = "ent_ammo_" .. ammo
                    AmmoCount = math_random(hg.ammoents[ammo].Count or 30)
                end
            else
                local ammoKey = string_Replace(entName, "ent_ammo_", "")
                local tbl = hg.ammotypeshuy[ammoKey]
                local ammoName = tbl and tbl.name
                AmmoCount = math_random(ammoName and hg.ammoents[ammoName] and hg.ammoents[ammoName].Count or 30)
            end
        elseif entName == "*attachments*" then
            local tbl = table.GetKeys(table.Random(hg.validattachments))
            local att = tbl[math_random(#tbl)]
            entName = "ent_att_" .. att
            Tab = "Attachments"
        elseif entName == "*sight*" then
            local tbl = table.GetKeys(hg.validattachments.sight)
            local att = tbl[math_random(#tbl)]
            entName = "ent_att_" .. att
            Tab = "Attachments"
        elseif entName == "*barrel*" then
            local tbl = table.GetKeys(hg.validattachments.barrel)
            local att = tbl[math_random(#tbl)]
            entName = "ent_att_" .. att
            Tab = "Attachments"
        end

        if not entName then return end
        if string_find(entName, "*", 1, true) then return end

        if string_find(entName, "ent_armor_", 1, true) then
            Tab = "Armor"
        end

        if func then
            return func(entName, AmmoCount, Tab)
        end

        return entName, AmmoCount, Tab
    end
end

